def collect(db_path, season, week, now):
    if not os.path.isfile(db_path):
        raise Refused(1, f"database not found: {db_path}")
    conn = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    try:
        cols = [r[1] for r in conn.execute("PRAGMA table_info(leans)")]
        if not cols:
            raise Refused(1, "leans table missing")
        n = conn.execute("SELECT COUNT(*) FROM leans WHERE season=? AND week=?", (season, week)).fetchone()[0]
        if n == 0:
            raise Refused(3, f"no leans stored for {season} week {week}")
        if "run_id" not in cols:
            raise Refused(4, "leans have no provenance columns (pre-migration-4 database)")
        bad = conn.execute(
            "SELECT COUNT(*) FROM leans WHERE season=? AND week=? AND (run_id IS NULL OR code_sha IS NULL "
            "OR forecast_version IS NULL OR forecast_version NOT LIKE ?)",
            (season, week, pc.FOOTBALL_ONLY_PREFIX + "%")).fetchone()[0]
        if bad:
            raise Refused(4, f"{bad} lean(s) for {season} week {week} lack football-only provenance")
        payload = pc.week_cards(conn, season, week, now=now)
        runs = [dict(zip(("run_id", "code_sha", "forecast_version", "ranker_sha256", "clock", "as_of",
                          "created_at"), r)) for r in conn.execute(
            "SELECT DISTINCT run_id, code_sha, forecast_version, ranker_sha256, clock, as_of, created_at "
            "FROM leans WHERE season=? AND week=? ORDER BY created_at", (season, week))]
        q = conn.execute("SELECT MIN(quote_ts), MAX(quote_ts), COUNT(quote_ts) FROM leans "
                         "WHERE season=? AND week=?", (season, week)).fetchone()
    except sqlite3.DatabaseError as exc:
        raise Refused(1, f"database unreadable: {exc}")
    finally:
        conn.close()
    payload["runs"] = runs
    from nflvalue import factor_integration as fimod
    conn = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    try:
        payload["factor_receipts"] = list(fimod.load_receipts(conn, season, week).values())
        on_board = {r["run_id"] for r in runs}
        ctx = [r for (run, _g), rs in fimod.load_context_records(conn, season, week).items()
               if run in on_board for r in rs]
    finally:
        conn.close()
    clocks = sorted(r["fetched_at"] for r in ctx if r.get("fetched_at"))
    payload["context_captured"] = (f"primary-source fetches up to {clocks[-1]}" if clocks else None)
    payload["quote_clocks"] = {"earliest": q[0], "latest": q[1], "leans_with_quote": q[2]}
    return payload


