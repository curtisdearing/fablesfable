ARCHIVE_PATTERNS = [
    re.compile(r"reports/[0-9]{4}/week-(?:[1-9]|1[0-9]|2[0-2])\.html\Z"),
    re.compile(r"games/[0-9]{4}_[0-9]{2}_[A-Za-z]{2,3}_[A-Za-z]{2,3}\.html\Z"),
    re.compile(r"games/(?:pages|index)\.json\Z"),
    re.compile(r"(?:history|dashboard)\.html\Z"),
    re.compile(r"assets/(?:[^/]+/)*[^/]+\.(?:css|js|svg|png|ico)\Z"),
]
LABELS = {
    "fresh": "Generated by a scheduled production run from the quotes it captured.",
    "replay": ("REPLAY: the full production pipeline re-run on final code against quotes captured "
               "earlier (clocks below). Prices may have moved since capture."),
}
