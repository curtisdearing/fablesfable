    e = html.escape
    parts = [f"<h1>Issued-pick results</h1><p>Settlement checked {e(str(doc.get('results_checked_at')))}. "
             f"{e(doc['note'])}</p>"]
    for name, sec in doc["sections"].items():
        rows = sec["rows"]
        c = sec.get("counts") or {}
        parts.append(f"<h2>{e(SETTLEMENT_LABELS.get(name, name))}</h2>")
        if not rows:
            parts.append("<p>None settled.</p>")
